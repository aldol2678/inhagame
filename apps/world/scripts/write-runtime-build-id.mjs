import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function resolveRuntimeBuildId({ deploymentSha = process.env.VERCEL_GIT_COMMIT_SHA,
  readGit = () => execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim() } = {}) {
  const value = deploymentSha || readGit();
  if (typeof value !== 'string' || !/^[a-f0-9]{40}$/.test(value)) throw new Error('Invalid runtime build identifier');
  return value;
}
export async function writeRuntimeBuildId(path = new URL('../src/diagnostics/build-id.js', import.meta.url), options) {
  const id = resolveRuntimeBuildId(options);
  await writeFile(path, `// Generated by write-runtime-build-id.mjs.\nexport const WORLD_BUILD_ID = '${id}';\n`);
  return id;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await writeRuntimeBuildId();
