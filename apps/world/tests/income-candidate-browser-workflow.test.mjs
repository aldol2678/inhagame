import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createFakeDocument } from './support/fake-dom.mjs';
const read = p => readFile(new URL(p, import.meta.url), 'utf8');
test('browser candidate workflow pins head, uses readonly permissions and uploads failure evidence', async () => {
  const workflow = await read('../../../.github/workflows/income-candidate-browser.yml');
  assert.match(workflow, /contents: read/); assert.match(workflow, /persist-credentials: false/);
  assert.match(workflow, /ref: \$\{\{ github.event.pull_request.head.sha \|\| github.sha \}\}/);
  assert.match(workflow, /EXPECTED_INCOME_HEAD:/);
  for (const source of ['delivery-income', 'world-income-candidate.js', 'dev-server.mjs', 'dev/income-candidate']) assert.ok(workflow.includes(source)); assert.match(workflow, /if: always\(\)/);
  assert.doesNotMatch(workflow, /pull_request_target|secrets\.|permissions:\s*write|deploy/i);
  const smoke = await read('./browser/income-candidate-smoke.mjs');
  for (const contract of ['productionEvidence: false', 'servedSourceHashes', 'report.expectedHead', "serviceWorkers: 'block'", "route.abort('blockedbyclient')", "url.pathname.startsWith('/api/')", 'result.json']) assert.ok(smoke.includes(contract), contract);
});
test('browser fixture exercises actual mount → both panels → HTTP → auth handler → synthetic RPC, without network', async () => {
  const source = await read('./browser/income-candidate-fixture.mjs');
  for (const name of ['mountIncomeCandidate', 'createConfiguredIncomeCandidateHandler', 'mockRpc']) assert.ok(source.includes(name));
  assert.doesNotMatch(source, /\bfetch\s*\(|https:\/\//);
  assert.match(source, /synthetic-fixture-not-a-credential/);
  const oldDoc = globalThis.document, oldWindow = globalThis.window, oldStorage = globalThis.sessionStorage;
  const doc = createFakeDocument(); doc.body = doc.createElement('body');
  const ids = new Map(['candidate-root', 'outside', 'ready'].map(id => { const node = doc.createElement('button'); node.id = id; doc.body.append(node); return [id, node]; }));
  doc.getElementById = id => ids.get(id);
  const storage = new Map();
  globalThis.document = doc; globalThis.window = { addEventListener() {}, removeEventListener() {} };
  globalThis.sessionStorage = { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v) };
  try {
    await import('./browser/income-candidate-fixture.mjs');
    const h = window.__INCOME_FIXTURE__; await h.ready; await h.scenario('fresh');
    const root = ids.get('candidate-root');
    root.children.find(n => n.textContent === '편의점 후보 검토').click(); assert.equal(h.ui.open, true);
    root.children.find(n => n.textContent === '납품 후보 검토').click(); assert.equal(h.ui.open, false);
    assert.ok(doc.body.children.some(n => n.className?.includes('delivery-income-panel') && !n.hidden));
    await h.client.refresh(); await h.delivery.refresh();
    assert.equal(h.state().phase, 'POSTING'); await h.client.start(); assert.equal(h.state().phase, 'WORKING');
    await h.client.choose('rushed'); assert.equal(h.state().notice, 'WRONG_CHOICE'); assert.equal(h.state().snapshot.session.revision, 0);
    for (let i = 0; i < 3; i++) await h.client.choose('careful'); assert.equal(h.state().phase, 'CHECKOUT');
    h.loseNextFinish(); await h.client.complete(); assert.equal(h.state().phase, 'RECOVERY'); assert.equal(h.commits.length, 0);
    await h.client.refresh(); assert.equal(h.state().phase, 'CONFIRMED'); assert.equal(h.commits.length, 1);
    assert.equal(h.calls.filter(c => c.name === 'world_income_finish_v1').length, 1);
    await h.scenario('checkout'); h.holdNext('world_income_finish_v1'); const finishing = h.client.complete();
    for (let i = 0; i < 10 && !h.held(); i++) await Promise.resolve(); assert.equal(h.held(), true);
    assert.equal((await h.client.complete()).outcome, 'BUSY'); await h.switchAccount(); h.release(); await finishing;
    assert.equal(h.commits.length, 0); assert.equal(h.state().phase, 'POSTING');
    await h.scenario('dailyLimit'); assert.equal((await h.client.start()).outcome, 'REFUSED');
    await h.scenario('expired'); assert.equal(h.state().phase, 'POSTING'); await h.client.start(); assert.equal(h.state().phase, 'WORKING');
    await h.scenario('closedReceipt'); assert.equal(h.state().phase, 'CONFIRMED'); assert.equal((await h.client.start()).outcome, 'REFUSED');
    await h.scenario('fresh'); await h.delivery.accept(); assert.equal(h.delivery.state().snapshot.ownedQuantity, 2);
    await h.delivery.submit(); assert.equal(h.delivery.state().snapshot.receipt.coin, 20); assert.equal(h.delivery.state().snapshot.ownedQuantity, 1);
    assert.equal(h.deliveryCommits.length, 1); assert.ok(h.httpCalls.every(c => !('accountId' in c.body) && !('coin' in c.body)));
    await h.scenario('deliveryInsufficient'); await h.delivery.accept(); assert.equal(h.delivery.state().snapshot.ownedQuantity, 0);
    assert.equal(await h.delivery.submit(), false);
    await h.scenario('fresh'); await h.delivery.accept(); h.loseNextFinish(); await h.delivery.submit();
    assert.ok(h.delivery.state().error); assert.equal(h.deliveryCommits.length, 0); await h.delivery.refresh();
    assert.equal(h.delivery.state().snapshot.receipt.coin, 20); assert.equal(h.delivery.state().snapshot.ownedQuantity, 1);
    assert.equal(h.calls.filter(c => c.name === 'world_income_finish_v1').length, 1);
    h.ui.dispose();
  } finally { globalThis.document = oldDoc; globalThis.window = oldWindow; globalThis.sessionStorage = oldStorage; }
});
