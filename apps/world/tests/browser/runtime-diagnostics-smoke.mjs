import { openSettingsCategory } from './settings-navigation.mjs';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { startSmoke, TIMEOUT_MS } from './harness.mjs';
const output = process.env.RUNTIME_DIAGNOSTICS_OUTPUT || 'test-results/runtime-diagnostics';
await mkdir(output, { recursive: true });
const evidence = { head: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), cases: [] };
let smoke;
const action = (page, name) => page.locator(`[data-action="${name}"]`);
const get = page => page.evaluate(() => window.__RUNTIME_FIXTURE__.snapshot());
try {
  for (const [name, viewport, mobile] of [['desktop', { width: 1280, height: 800 }, false],
    ['portrait', { width: 360, height: 800 }, true], ['landscape', { width: 800, height: 360 }, true]]) {
    smoke = await startSmoke({ viewport, contextOptions: { isMobile: mobile, hasTouch: mobile } });
    const page = await smoke.context.newPage(); await page.setViewportSize(viewport);
    await page.goto(`${smoke.origin}/tests/browser/runtime-diagnostics-harness.html`);
    await page.waitForFunction(() => !!window.__RUNTIME_FIXTURE__);
    const pageErrors = []; page.on('pageerror', error => pageErrors.push(error.message));
    const press = locator => mobile ? locator.tap() : locator.click();
    await press(page.locator('#opener'));
    await page.waitForFunction(() => window.__RUNTIME_FIXTURE__.snapshot().diagnostics.fps !== null);
    let state = await get(page);
    assert.equal(state.movement, false); assert.equal(state.camera, false); assert.equal(state.focus.textInput, true);
    assert.deepEqual(state.copies, []);
    assert.equal(await action(page, 'export').isDisabled(), true);
    await page.locator('#diagnostics-description').fill('정문 화면이 멈춰요 player@example.test');
    await page.locator('#diagnostics-description').press('KeyM');
    assert.equal((await get(page)).shortcutCount, 0, 'typing cannot trigger gameplay shortcut');
    const beforeTicks = (await get(page)).gameTicks;
    await page.evaluate(() => {
      const error = new Error('email=private@example.test accountId=private-id token=secret');
      setTimeout(() => { throw error; }, 0);
      void Promise.reject(new Error('synthetic rejected task secret-token'));
      window.__RUNTIME_FIXTURE__.device.fire('devicelost', { message: 'private renderer error' });
      window.__RUNTIME_FIXTURE__.setNetwork('RECONNECTING');
    });
    await page.waitForFunction(() => window.__RUNTIME_FIXTURE__.snapshot().diagnostics.recentErrors.some(e => e.code === 'RUNTIME_PROMISE_REJECTION'));
    await press(action(page, 'refresh'));
    assert.match(await page.locator('[data-health]').textContent(), /그래픽/);
    await page.evaluate(() => window.__RUNTIME_FIXTURE__.setNetwork('OFFLINE'));
    await press(action(page, 'refresh'));
    state = await get(page);
    assert.equal(state.diagnostics.rendererState, 'LOST'); assert.equal(state.diagnostics.network, 'OFFLINE');
    assert.ok(state.diagnostics.recentErrors.some(e => e.code === 'RUNTIME_SCRIPT_ERROR'));
    assert.ok(state.diagnostics.recentErrors.some(e => e.code === 'RUNTIME_PROMISE_REJECTION'));
    await page.waitForFunction(ticks => window.__RUNTIME_FIXTURE__.snapshot().gameTicks > ticks + 3, beforeTicks);
    await page.locator('#diagnostics-reproduction').fill('설정 → 진단 열기');
    await page.locator('#diagnostics-context').fill('cookie: never-export-this\n휴대폰 가로 화면');
    await press(action(page, 'generate'));
    const text = await page.locator('[data-preview]').inputValue();
    const report = JSON.parse(text);
    assert.doesNotMatch(text, /player@|private@|private-id|secret|never-export-this|raw private stack/);
    assert.equal(report.diagnostics.zoneId, 'AREA_MAIN_GATE');
    assert.equal((await get(page)).copies.length, 0, 'generation itself does not export');
    await press(action(page, 'copy'));
    assert.equal((await get(page)).copies[0], text);
    const downloadEvent = page.waitForEvent('download'); await press(action(page, 'export'));
    const download = await downloadEvent;
    assert.equal(download.suggestedFilename(), 'inha-world-bug-report.json');
    assert.deepEqual(JSON.parse(await readFile(await download.path(), 'utf8')), report);
    await page.evaluate(() => window.__RUNTIME_FIXTURE__.copyFailure(true));
    await press(action(page, 'copy'));
    await page.waitForFunction(() => document.querySelector('[data-notice]').textContent.includes('직접 복사'));
    assert.equal(await page.locator('[data-preview]').evaluate(el => el.selectionStart === 0 && el.selectionEnd === el.value.length), true);
    await page.evaluate(() => { const f = window.__RUNTIME_FIXTURE__; f.copyFailure(false); f.deferCopy(); });
    await press(action(page, 'copy'));
    await page.evaluate(() => window.__RUNTIME_FIXTURE__.setIdentity());
    assert.equal(await page.locator('#runtime-diagnostics-panel').isVisible(), false);
    assert.deepEqual((await get(page)).diagnostics.recentErrors, []);
    await page.evaluate(() => window.__RUNTIME_FIXTURE__.settleCopy());
    await press(page.locator('#opener'));
    assert.equal(await page.locator('#diagnostics-description').inputValue(), '');
    assert.equal(await page.locator('[data-preview]').inputValue(), '');
    assert.equal(await page.locator('[data-notice]').textContent(), '');
    assert.equal(await action(page, 'copy').isDisabled(), true);
    await page.locator('#diagnostics-description').fill('new draft');
    await page.evaluate(() => window.__RUNTIME_FIXTURE__.signOut());
    await press(page.locator('#opener'));
    assert.equal(await page.locator('#diagnostics-description').inputValue(), '');
    // Native dialog trap, explicit Escape and ownership handback.
    await page.locator('[data-action="close"]').focus(); await page.keyboard.press('Shift+Tab');
    assert.equal(await page.locator('#runtime-diagnostics-panel').evaluate(el => el.contains(document.activeElement)), true);
    const box = await page.locator('#runtime-diagnostics-panel').boundingBox();
    assert.ok(box.x >= 0 && box.width <= viewport.width && box.y >= 0 && box.y + box.height <= viewport.height + 1);
    await page.screenshot({ path: join(output, `${name}.png`) });
    await page.keyboard.press('Escape');
    assert.equal((await get(page)).movement, true); assert.equal((await get(page)).camera, true);
    await page.keyboard.press('KeyM'); assert.equal((await get(page)).shortcutCount, 1);
    assert.deepEqual(await page.evaluate(() => window.__RUNTIME_FIXTURE__.dispose()), { app: 0, device: 0 });
    assert.deepEqual(pageErrors.sort(), ['email=private@example.test accountId=private-id token=secret', 'synthetic rejected task secret-token'].sort());
    evidence.cases.push({ name, viewport, passed: true }); console.log(`runtime diagnostics fixture: PASS (${name})`);
    await page.close(); await smoke.close(); smoke = null;
  }
  // Real campus composition, real settings/menu, real rendering and real trusted mobile touch.
  smoke = await startSmoke({ viewport: { width: 360, height: 800 }, contextOptions: { isMobile: true, hasTouch: true } });
  const page = await smoke.context.newPage();
  const fatal = smoke.watch(page);
  await page.goto(`${smoke.origin}/campus/?lobby=1`, { waitUntil: 'domcontentloaded', timeout: TIMEOUT_MS });
  await Promise.race([page.waitForFunction(() => !!window.__INHA_WORLD_RUNTIME_DIAGNOSTICS__, null, { timeout: TIMEOUT_MS }), fatal]);
  await page.locator('#world-loading').waitFor({ state: 'hidden' });
  await page.locator('#lobby-menu-toggle').tap(); await page.locator('#lobby-open-settings').tap();
  await openSettingsCategory(page, 'diagnostics', { touch: true });
  await page.locator('#open-runtime-diagnostics').tap();
  assert.equal(await page.locator('#runtime-diagnostics-panel').isVisible(), true);
  assert.equal(await page.locator('#view-settings').isVisible(), false);
  const live = await page.evaluate(() => window.__INHA_WORLD_RUNTIME_DIAGNOSTICS__.status());
  assert.ok(['WebGL2', 'WebGPU'].includes(live.renderer)); assert.equal(live.worldId, 'LOBBY');
  await smoke.context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: smoke.origin });
  await page.locator('#diagnostics-description').fill('실제 모바일 설정 화면에서 보고서를 만들어요.');
  await action(page, 'generate').tap(); await action(page, 'copy').tap();
  await page.waitForFunction(() => document.querySelector('[data-notice]').textContent.includes('복사했어요'));
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await page.locator('[data-preview]').inputValue());
  await action(page, 'close').tap();
  assert.equal(await page.locator('#lobby-menu-toggle').evaluate(el => el === document.activeElement), true);
  await page.locator('#main-gate-start').tap();
  await page.waitForFunction(() => {
    const d = window.__INHAGAME_P0__; return !d.lobbyWorld.active && !d.getStatus().cinematic?.active && d.controller.inputEnabled;
  }, null, { timeout: TIMEOUT_MS });
  await page.locator('#hud-menu-toggle').tap(); await page.locator('#open-settings').tap();
  await openSettingsCategory(page, 'diagnostics', { touch: true });
  await page.locator('#open-runtime-diagnostics').tap();
  assert.equal(await page.evaluate(() => window.__INHAGAME_P0__.controller.inputEnabled), false);
  await action(page, 'close').tap();
  assert.equal(await page.evaluate(() => window.__INHAGAME_P0__.controller.inputEnabled), true);
  assert.deepEqual(smoke.problems, []);
  evidence.cases.push({ name: 'campus-settings-lobby-hud', passed: true });
  console.log('runtime diagnostics campus integration: PASS');
} finally {
  await writeFile(join(output, 'results.json'), JSON.stringify(evidence, null, 2)); await smoke?.close();
}
